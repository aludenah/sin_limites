'use strict';
// Source transcription, independent numerical checks and all ten answer keys.
require('./pdf-electromagnetism-practice.test.cjs');
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path'),vm=require('node:vm');
const root=path.join(__dirname,'..'),context={window:{}};
for(const file of ['practice-bank.js','fisica-capitulo-17-practice.js','chapter-practice.js'])vm.runInNewContext(fs.readFileSync(path.join(root,file),'utf8'),context,{filename:file});
const id='fisica-capitulo-17',api=context.window.ChapterPractice,questions=api.questions(id);
const p=api.normalize(id),first=questions[0],last=questions[9];
assert.equal(api.check(id,p,first.id,'progressive'),'missing');
assert.equal(p.mastered.length,0);
assert.equal(api.choose(id,p,last.id,last.answer,'progressive'),false,'Progressive practice must unlock questions in order');
assert.equal(api.choose(id,p,first.id,(first.answer+1)%5,'progressive'),true);
assert.equal(api.check(id,p,first.id,'progressive'),'graded');
assert.equal(p.mastered.length,0);
assert.equal(p.attempts[first.id],1);
assert.equal(api.check(id,p,first.id,'progressive'),'unchanged','Repeated submission of the same choice does not inflate attempts');
assert.equal(api.choose(id,p,first.id,first.answer,'progressive'),true);
assert.equal(api.check(id,p,first.id,'progressive'),'graded');
assert.equal(p.mastered.length,1);
assert.equal(p.attempts[first.id],2);
assert.equal(api.canOpen(id,p,1,'progressive'),true);
assert.equal(api.summary(id,{practice10:p}).percent,10);
// Retrying a mastered question never deletes the student's earned success.
api.choose(id,p,first.id,(first.answer+1)%5,'progressive');api.check(id,p,first.id,'progressive');
assert.equal(p.mastered.includes(first.id),true);
const reloaded=api.normalize(id,{practice10:p});
assert.equal(reloaded.mastered.includes(first.id),true);
assert.equal(reloaded.attempts[first.id],3);
assert.equal(api.canOpen(id,reloaded,9,'free'),true);
const remote=api.normalize(id);api.choose(id,remote,last.id,last.answer,'free');api.check(id,remote,last.id,'free');
const merged=api.merge(id,{updatedMs:100,practice10:p},{updatedMs:10,practice10:remote});
assert.deepEqual(new Set(merged.practice10.mastered),new Set([first.id,last.id]),'Achievements from both devices survive an older cloud snapshot');
assert.equal(merged.practice10.attempts[first.id],3);
assert.equal(api.summary(id,merged).percent,20);
console.log('PASS: source practice retries, progressive/free access, reload, retained achievements and cross-device merge.');
